// الملف ده نقي عن قصد (بلا DI وبلا decorators): الخدمة والاختبارات بيقروا منه نفس المفردات.

/** مفتاح requests_config اللي بيقفل/يفتح التزويد التلقائي عند إضافة موظف. الافتراضي **مفتوح**. */
export const DOMAIN_AUTOPROVISION_CONFIG_KEY = 'auth.domain_autoprovision_enabled'

/**
 * القيمة اللي بتتبذر مع المفتاح: مفتوح، لأن الدخول بالدومين شغّال حيًّا خلاص (827 حساب،
 * 377 حساب اتعملوا في المزامنة الجماعية) — فالموظف الجديد المفروض ياخد حسابه في لحظته.
 */
export const DOMAIN_AUTOPROVISION_DEFAULT = 'true'

/** القيم اللي بتقفل المفتاح — القفل لازم ينجح مهما كتبها المالك، وأي قيمة تانية = الافتراضي (مفتوح). */
const OFF_VALUES = new Set(['false', '0', 'no', 'off'])

/**
 * التزويد التلقائي مفتوح؟ المفتاح الناقص (أو قراءة فشلت) = مفتوح — ده الافتراضي المعلن،
 * وConfigDefaultsService بيبذره عند أول إقلاع. القفل بيحصل بقيمة صريحة بس.
 */
export function domainAutoProvisionEnabled(value?: string | null): boolean {
  return !OFF_VALUES.has(String(value ?? '').trim().toLowerCase())
}

