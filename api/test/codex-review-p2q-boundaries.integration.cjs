'use strict'
const {test,before,after}=require('node:test'),assert=require('node:assert/strict')
let f
before(async()=>{f=await require('./codex-review-p2q-comments-fixture.cjs')('p2q_boundaries')},{timeout:180000})
after(async()=>{if(f)await f.close()})
test('P2Q internal attachment must obey current comment visibility after its uploader becomes the requester',async t=>{
 const subject=await f.employee(f.A,{managerEmployeeId:f.manager.id}),owner=await f.account(subject)
 const req=await f.submit(f.proxyU,{onBehalfEmployeeId:subject.id}),u=await f.account(await f.employee(),['requests.view_all']),file=await f.upload(u)
 const written=await f.say(u,req.id,{body:'Synthetic internal content',internal:true,fileIds:[file.id]})
 assert.equal(written.status,201)
 assert.equal((await f.download(u,file.id)).status,200)
 assert.equal((await f.download(owner,file.id)).status,404)
 await f.ok('PATCH',`/users/${owner.id}`,{employeeId:null})
 await f.ok('PATCH',`/users/${u.id}`,{employeeId:subject.id})
 const current=await f.repo('User').findOneByOrFail({id:u.id})
 assert.equal((await f.thread(u,req.id)).status,401,'Old session is invalidated')
 const shown=await f.thread(current,req.id),download=await f.download(current,file.id)
 assert.equal(shown.status,200);assert.equal(shown.body.canInternal,false);assert.deepEqual(shown.body.comments,[])
 assert.equal((await f.say(current,req.id,{body:'Synthetic refused internal',internal:true})).status,400)
 t.diagnostic(JSON.stringify({case:'rebound-uploader-is-now-requester',threadComments:shown.body.comments.length,canInternal:shown.body.canInternal,fileStatus:download.status,fileBytesMatch:download.bytes.equals(f.png)}))
 assert.equal(download.status,404,'A bound internal attachment must be hidden just like its comment, even from an account that uploaded it before rebinding')
})
test('P2Q in-app mention must not retain a foreign request identifier after recipient account rebinding',async t=>{
 const owner=await f.employee(f.A,{managerEmployeeId:f.manager.id}),u=await f.account(owner)
 const req=await f.submit(f.proxyU,{onBehalfEmployeeId:owner.id})
 const said=await f.say(f.managerU,req.id,{body:'Synthetic public reply',targets:['REQUESTER']});assert.equal(said.status,201)
 await f.dispatch(said.body.ref)
 const before=await f.ok('GET','/notifications',null,u),link=`/requests?request=${req.id}`
 assert.ok(JSON.stringify(before).includes(link),'Visible recipient gets a usable notification link')
 const other=await f.employee(f.B)
 await f.ok('PATCH',`/users/${u.id}`,{employeeId:other.id,branchId:f.B.id})
 const rebound=await f.repo('User').findOneByOrFail({id:u.id})
 const detail=await f.request('GET',`/requests/${req.id}`,null,rebound),thread=await f.thread(rebound,req.id)
 assert.equal(detail.status,404);assert.equal(thread.status,404)
 const after=await f.ok('GET','/notifications',null,rebound)
 t.diagnostic(JSON.stringify({case:'foreign-link-after-account-rebinding',detailStatus:detail.status,threadStatus:thread.status,foreignLinkRetained:JSON.stringify(after).includes(link)}))
 assert.equal(JSON.stringify(after).includes(link),false,'An opaque generic alert must not retain the ID of a request the current account identity cannot see')
})
test('P2Q ordinary file owner remains allowed while an unbound upload is private to that account',async()=>{
 const file=await f.upload(f.hrU)
 assert.equal((await f.download(f.hrU,file.id)).status,200)
 assert.equal((await f.download(f.workerU,file.id)).status,404)
 assert.equal((await f.download(f.admin,file.id)).status,404)
})
test('P2Q request made on behalf: unlinking its owner account must not reveal internal comments to that same account',async t=>{
 const subject=await f.employee(f.A,{managerEmployeeId:f.manager.id}),u=await f.account(subject,['requests.view_all'])
 const req=await f.submit(f.proxyU,{onBehalfEmployeeId:subject.id})
 const internal=await f.say(f.managerU,req.id,{body:'Synthetic private evaluation of requester',internal:true})
 assert.equal(internal.status,201)
 const before=await f.thread(u,req.id);assert.equal(before.status,200);assert.deepEqual(before.body.comments,[]);assert.equal(before.body.canInternal,false)
 await f.ok('PATCH',`/users/${u.id}`,{employeeId:null})
 const unlinked=await f.repo('User').findOneByOrFail({id:u.id})
 assert.equal((await f.thread(u,req.id)).status,401)
 const after=await f.thread(unlinked,req.id)
 assert.equal(after.status,200)
 t.diagnostic(JSON.stringify({case:'known-limit-on-behalf-owner-unlink',canInternal:after.body.canInternal,internalBodyVisible:JSON.stringify(after.body).includes(internal.body.body)}))
 assert.equal(JSON.stringify(after.body).includes(internal.body.body),false,'The same account must not gain the internal side of its own existing request by losing its employee binding')
})
