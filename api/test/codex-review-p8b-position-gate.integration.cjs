'use strict'
const {test,before,after}=require('node:test'),assert=require('node:assert/strict')
const {disposableApp}=require('./helpers/disposable-app.cjs')
const {moduleTools}=require('./helpers/modules.cjs')
const t=disposableApp('p8b_positions')
before(()=>t.start(),{timeout:120000}); after(c=>t.stop(c))
test('P8B-J01: vacancy route bypasses recruitment module audience',async()=>{
  const a=await t.repo('Branch').save({code:'P8B_JA',name:'P8B A'})
  const b=await t.repo('Branch').save({code:'P8B_JB',name:'P8B B'})
  const emp=await t.repo('Employee').save({employeeCode:'P8B_J',fullName:'P8B recruiter',branchId:a.id,joinDate:'2020-01-01',basicSalary:1000,status:'active',isActive:true})
  const admin=await t.user({scopeAllBranches:true})
  const user=await t.user({role:'employee',employeeId:emp.id,branchId:a.id,permissions:JSON.stringify(['positions.view','positions.manage','candidates.manage'])})
  const modules=moduleTools(t.app)
  await modules.enable('positions')
  await modules.enable('recruitment',{who:{mode:'all'},where:{mode:'branches',ids:[b.id]}})
  const title=await t.repo('JobTitle').save({title:'P8B programmer',isActive:true})
  const position=t.expectStatus(await t.request(admin,'POST','/positions',{jobTitleId:title.id,branchId:a.id,headcount:2}),201)
  const original=await t.request(user,'GET','/recruitment/jobs')
  assert.equal(original.status,404,JSON.stringify(original.body))
  const opened=await t.request(user,'POST','/positions/'+position.id+'/open-job',{openings:1})
  console.log('REVIEW_MEASURE '+JSON.stringify({case:'P8B-J01',original:original.status,alternate:opened.status,jobId:opened.body.jobId}))
  assert.equal(opened.status,400)
  assert.equal(await t.repo('RecruitmentJob').count(),0); const view=t.expectStatus(await t.request(user,'GET','/positions/hiring-suggestions'),200); assert.equal(view.recruitment,false);assert.equal(view.canOpen,false)
})
